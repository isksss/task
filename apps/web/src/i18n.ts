export function clearDeviceDataConfirmation(t: Translation, pendingChanges: number): string {
  return pendingChanges > 0
    ? t.confirmClearDeviceDataPending.replace("{count}", String(pendingChanges))
    : t.confirmClearDeviceData;
}

export const dictionaries: Record<Locale, Translation> = { ja, en };

export function getDefaultLocale(language?: string): Locale {
  const browserLanguage = language ?? (typeof navigator === "undefined" ? "" : navigator.language);
  return browserLanguage.toLowerCase().split("-")[0] === "en" ? "en" : "ja";
}
